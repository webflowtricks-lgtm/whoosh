export function getDefaultEventTheme(event: Pick<NinjaEvent, 'id' | 'title' | 'badge'>): NinjaEventTheme {
  if (
    event.id === UCHIHA_EVENT_ID ||
    `${event.id} ${event.title} ${event.badge}`.toLocaleLowerCase().includes('uchiha')
  ) return 'uchiha-red';
  if (`${event.id} ${event.title} ${event.badge}`.toLocaleLowerCase().includes('naruto')) return 'naruto-orange';
  return 'naruto-orange';
}

export function getEventTheme(themeId: NinjaEventTheme | undefined): EventThemeOption {
  return EVENT_THEMES.find(theme => theme.id === themeId) || EVENT_THEMES[0];
}

